ROUTE_PERMISSIONS = {
    operation: key for key, operations in OPERATIONS.items() for operation in operations
}


# Match the fully mounted URL: nested FastAPI routers expose a local route.path.
# Static routes are checked first, then the registered parameterized templates.
PARAMETERIZED_POLICIES = [
    (
        method,
        re.compile(
            "^"
            + "".join(
                "[^/]+" if part.startswith("{") else re.escape(part)
                for part in re.split(r"(\{[^}]+\})", path)
            )
            + "$"
        ),
        permission,
    )
    for (method, path), permission in ROUTE_PERMISSIONS.items()
    if "{" in path
]


def route_permission(method: str, path: str) -> str | None:
    method = method.upper()
    exact = ROUTE_PERMISSIONS.get((method, path))
    if exact:
        return exact
    return next(
        (
            permission
            for verb, pattern, permission in PARAMETERIZED_POLICIES
            if verb == method and pattern.fullmatch(path)
        ),
        None,
    )
