"""External steps are at-most-once attempts with durable unknown and confirmed receipts."""

SQL = (
    "CREATE TABLE integration_external_executions (\n"
    "\ttask_id VARCHAR(36) NOT NULL, \n"
    "\towner_user_id VARCHAR(36) NOT NULL, \n"
    "\tintent_id VARCHAR(36) NOT NULL, \n"
    "\tinput_sha256 VARCHAR(64) NOT NULL, \n"
    "\tconnection_id VARCHAR(100) NOT NULL, \n"
    "\tconnection_revision INTEGER NOT NULL, \n"
    "\tdocument_id VARCHAR(200) NOT NULL, \n"
    "\tpayload JSON NOT NULL, \n"
    "\tcheckpoint JSON NOT NULL, \n"
    "\tstatus VARCHAR(24) NOT NULL, \n"
    "\tcreated_at DATETIME NOT NULL, \n"
    "\tPRIMARY KEY (task_id), \n"
    "\tUNIQUE (intent_id)\n"
    ");\n"
    "CREATE INDEX ix_integration_external_executions_owner_user_id ON integration"
    "_external_executions (owner_user_id);\n"
    "CREATE UNIQUE INDEX uq_integration_external_active_document ON integration_e"
    "xternal_executions (document_id) WHERE status IN ('active', 'unknown');\n"
    "CREATE TABLE integration_external_step_receipts (\n"
    "\tid VARCHAR(36) NOT NULL, \n"
    "\towner_user_id VARCHAR(36) NOT NULL, \n"
    "\ttask_id VARCHAR(36) NOT NULL, \n"
    "\taction_key VARCHAR(250) NOT NULL, \n"
    "\tfingerprint VARCHAR(64) NOT NULL, \n"
    "\tstatus VARCHAR(24) NOT NULL, \n"
    "\tresult JSON NOT NULL, \n"
    "\tcreated_at DATETIME NOT NULL, \n"
    "\tupdated_at DATETIME NOT NULL, \n"
    "\tPRIMARY KEY (id), \n"
    "\tUNIQUE (task_id, action_key), \n"
    "\tFOREIGN KEY(task_id) REFERENCES integration_external_executions (task_id) O"
    "N DELETE CASCADE\n"
    ");\n"
    "CREATE INDEX ix_integration_external_step_receipts_owner_user_id ON integrat"
    "ion_external_step_receipts (owner_user_id);\n"
    "CREATE INDEX ix_integration_external_step_receipts_task_id ON integration_ex"
    "ternal_step_receipts (task_id);\n"
)
