HEADER = "# Generated by scripts/generate_sdk.py; do not edit.\n"


def identifier(value):
    value = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", value)
    value = re.sub(r"\W", "_", value).lower()
    return value + "_" if keyword.iskeyword(value) else value


def model_name(value):
    return re.sub(r"\W", "_", value)


def annotation(schema, *, prefix=""):
    if "$ref" in schema:
        return prefix + model_name(schema["$ref"].rsplit("/", 1)[-1])
    if "const" in schema:
        return f"Literal[{schema['const']!r}]"
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(x) for x in schema["enum"]) + "]"
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(
            dict.fromkeys(
                annotation(x, prefix=prefix) for x in schema.get("anyOf", schema.get("oneOf", []))
            )
        )
    kind = schema.get("type")
    if kind == "array":
        return "list[" + annotation(schema.get("items", {}), prefix=prefix) + "]"
    if kind == "object" or "properties" in schema:
        extra = schema.get("additionalProperties", {})
        return (
            "dict[str, " + annotation(extra if isinstance(extra, dict) else {}, prefix=prefix) + "]"
        )
    if schema.get("format") == "date-time":
        return "datetime"
    if schema.get("format") == "date":
        return "date"
    return {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "null": "None",
    }.get(kind, "Any")


def models_source(schemas):
    lines = [
        HEADER,
        "from __future__ import annotations",
        "from datetime import date, datetime",
        "from typing import Any, Literal",
        "from pydantic import BaseModel, ConfigDict, Field, RootModel",
        "",
        "class WireModel(BaseModel):",
        "    model_config = ConfigDict(populate_by_name=True, extra='allow', "
        "protected_namespaces=())",
        "",
    ]
    names = []
    for name, schema in schemas.items():
        name = model_name(name)
        names.append(name)
        if "properties" not in schema:
            lines.extend([f"class {name}(RootModel[{annotation(schema)}]):", "    pass", ""])
            continue
        lines.append(f"class {name}(WireModel):")
        props = schema["properties"]
        if not props:
            lines.append("    pass")
        used = set()
        for key, value in props.items():
            field = identifier(key)
            if field in used:
                raise ValueError(f"Ambiguous Python field in {name}: {key}")
            used.add(field)
            required = key in schema.get("required", [])
            field_type = annotation(value)
            default = "..." if required else repr(value.get("default"))
            if not required and value.get("default") is None and "None" not in field_type:
                field_type += " | None"
            options = [f"default={default}", f"alias={key!r}"]
            if any(
                part in field.lower()
                for part in ("password", "secret", "token", "cookie", "api_key", "plaintext")
            ):
                options.append("repr=False")
            for source, target in [
                ("minimum", "ge"),
                ("maximum", "le"),
                ("exclusiveMinimum", "gt"),
                ("exclusiveMaximum", "lt"),
                ("minLength", "min_length"),
                ("maxLength", "max_length"),
                ("minItems", "min_length"),
                ("maxItems", "max_length"),
            ]:
                if source in value:
                    options.append(f"{target}={value[source]!r}")
            lines.append(f"    {field}: {field_type} = Field({', '.join(options)})")
        lines.append("")
    lines.extend([f"{name}.model_rebuild()" for name in names])
    return "\n".join(lines) + "\n"


def inventory(schema, existing):
    result = {}
    names = set()
    for path, item in schema["paths"].items():
        for method, operation in item.items():
            if method not in {"get", "post", "put", "patch", "delete", "head", "options"}:
                continue
            key = method.upper() + " " + path
            tag = (operation.get("tags") or ["system"])[0]
            resource = TAGS.get(tag, identifier(tag))
            name = operation["operationId"].split("_v1_")[0]
            if resource == "system":
                name = path.strip("/")
            entry = existing.get(key, {"resource": resource, "method": identifier(name)})
            identity = (entry["resource"], entry["method"])
            if identity in names:
                if key in existing:
                    raise ValueError(f"Duplicate method {identity}")
                entry["method"] += "_" + identifier(
                    path.strip("/").replace("{", "").replace("}", "")
                )
                identity = (entry["resource"], entry["method"])
            names.add(identity)
            result[key] = entry
    return result


def method_source(path, method, operation, entry, asynchronous):
    parameters = operation.get("parameters", [])
    signature = []
    tuples = []
    for parameter in parameters:
        name = identifier(parameter["name"])
        kind = annotation(parameter["schema"], prefix="models.")
        if not parameter.get("required"):
            kind += " | Unset = UNSET"
        signature.append(f"{name}: {kind}")
        tuples.append(f"({parameter['name']!r}, {parameter['in']!r}, {name})")
    content = operation.get("requestBody", {}).get("content", {})
    media_type = next(iter(content), "")
    if content:
        body_type = annotation(content[media_type].get("schema", {}), prefix="models.")
        suffix = "" if operation["requestBody"].get("required") else " | Unset = UNSET"
        signature.append(f"body: {body_type} | dict{suffix}")
    if media_type == "multipart/form-data":
        signature.append("files: dict | list | None = None")
    responses = operation.get("responses", {})
    success = next((v for k, v in responses.items() if k.startswith("2")), {})
    success_content = success.get("content", {})
    response_schema = success_content.get("application/json", {}).get("schema", {})
    result = annotation(response_schema, prefix="models.")
    returned = result
    if not success_content:
        returned = "Any"
    elif "text/event-stream" in success_content or path.endswith("/stream"):
        returned = "AsyncEventStream" if asynchronous else "EventStream"
        result = "Any"
    elif "application/json" not in success_content:
        returned = "AsyncDownload" if asynchronous else "Download"
        result = "Any"
    sig = ", *, " + ", ".join(signature) if signature else ""
    description = operation.get("summary", entry["method"]) + f". {method.upper()} {path}"
    await_ = "await " if asynchronous else ""
    call = [repr(method.upper()), repr(path), "parameters=[" + ", ".join(tuples) + "]"]
    if content:
        call += ["body=body", f"media_type={media_type!r}"]
    if media_type == "multipart/form-data":
        call += ["files=files"]
    call.append("response_type=" + result)
    return [
        f"    {'async ' if asynchronous else ''}def {entry['method']}(self{sig}) -> {returned}:",
        f"        {description!r}",
        f"        return {await_}self._client._call({', '.join(call)})",
        "",
    ]


def generate(schema, mapping):
    files = {
        TARGET / "models.py": models_source(schema["components"]["schemas"]),
        TARGET / "__init__.py": HEADER,
        MAPPING: json.dumps(mapping, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
    }
    groups = defaultdict(list)
    for key, entry in mapping.items():
        method, path = key.split(" ", 1)
        groups[entry["resource"]].append(
            (path, method.lower(), schema["paths"][path][method.lower()], entry)
        )
    init = [HEADER]
    sync_names, async_names = [], []
    for resource, operations in sorted(groups.items()):
        class_name = "".join(x.title() for x in resource.split("_"))
        lines = [
            HEADER,
            "from __future__ import annotations",
            "from datetime import date, datetime",
            "from typing import Any, Literal",
            "from .. import models",
            "from ...encoding import UNSET, Unset",
            "from ...streams import Download, AsyncDownload, EventStream, AsyncEventStream",
            "",
        ]
        for asynchronous in (False, True):
            name = ("Async" if asynchronous else "") + class_name
            lines += [
                f"class {name}:",
                "    def __init__(self, client):",
                "        self._client = client",
                "",
            ]
            for args in operations:
                lines += method_source(*args, asynchronous)
        files[TARGET / "resources" / f"{resource}.py"] = "\n".join(lines) + "\n"
        init.append(f"from .{resource} import {class_name}, Async{class_name}")
        sync_names.append(f"{resource!r}: {class_name}")
        async_names.append(f"{resource!r}: Async{class_name}")
    init += [
        "",
        "RESOURCES = {" + ", ".join(sync_names) + "}",
        "ASYNC_RESOURCES = {" + ", ".join(async_names) + "}",
        "",
        "class SyncResources:",
    ]
    init += ["    " + n.replace("'", "") for n in sync_names]
    init += ["", "class AsyncResources:"]
    init += ["    " + n.replace("'", "") for n in async_names]
    files[TARGET / "resources/__init__.py"] = "\n".join(init) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = json.loads(SCHEMA.read_text())
    existing = json.loads(MAPPING.read_text()) if MAPPING.exists() else {}
    mapping = inventory(schema, existing)
    agent = json.loads(
        (ROOT / "backend/app/console/governance/desktop_agent_operations.json").read_text()
    )
    for key, operation in agent["operations"].items():
        if mapping.get(key) != operation:
            raise SystemExit(f"Desktop agent allowlist is stale: {key}")
    files = generate(schema, mapping)
    stale = []
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Stale SDK artifacts: " + ", ".join(stale))
    print(f"SDK: {len(mapping)} named operations, {len(schema['components']['schemas'])} schemas")


if __name__ == "__main__":
    main()
