"""Reproducible small public image variants; never reads private runtime data."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import subprocess
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "web/public"
TARGET = PUBLIC / "brand/thumbnails"
MANIFEST = ROOT / "web/src/shared/lib/imageVariants.ts"


def generate(check=False):
    sources = sorted((PUBLIC / "brand").glob("*.png")) + sorted(
        (PUBLIC / "presentation-templates").glob("*.png")
    )
    variants = {}
    expected = set()
    for source in sources:
        payload = source.read_bytes()
        if payload.startswith(b"version https://git-lfs.github.com/spec/"):
            raise SystemExit(f"Missing LFS content: {source.relative_to(ROOT)}")
        digest = hashlib.sha256(payload).hexdigest()[:12]
        sizes = (64, 128, 256) if source.parent.name == "brand" else (320, 640, 1280)
        entries = {}
        with Image.open(io.BytesIO(payload)) as original:
            image = ImageOps.exif_transpose(original).convert("RGBA")
            for size in sizes:
                frame = image.copy()
                frame.thumbnail((size, size), Image.Resampling.LANCZOS)
                output = io.BytesIO()
                frame.save(output, format="WEBP", quality=76, method=4)
                target = TARGET / f"{source.stem}-{digest}-{size}.webp"
                expected.add(target)
                content = output.getvalue()
                if source.parent.name == "brand" and len(content) > 30 * 1024:
                    raise SystemExit(f"Icon exceeds 30 KB: {target.name}")
                if check:
                    if not target.exists() or target.read_bytes() != content:
                        raise SystemExit(f"Image variant stale: {target.relative_to(ROOT)}")
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(content)
                entries[str(size)] = "/" + target.relative_to(PUBLIC).as_posix()
        variants["/" + source.relative_to(PUBLIC).as_posix()] = entries
    content = (
        "// Generated by scripts/generate_image_variants.py; do not edit.\n"
        "export const imageVariants: Record<string, Record<string, string>> = "
        + json.dumps(variants, ensure_ascii=False, indent=2)
        + ";\n"
    )
    content = subprocess.run(
        ["node", str(ROOT / "node_modules/prettier/bin/prettier.cjs"), "--parser", "typescript"],
        input=content,
        text=True,
        check=True,
        capture_output=True,
    ).stdout
    if check:
        if not MANIFEST.exists() or MANIFEST.read_text() != content:
            raise SystemExit("Image variant manifest stale")
        if set(TARGET.glob("*.webp")) != expected:
            raise SystemExit("Unexpected stale image variants")
    else:
        MANIFEST.write_text(content)
        for stale in set(TARGET.glob("*.webp")) - expected:
            stale.unlink()
    print(
        f"Verified {len(sources)} public images, {len(expected)} variants"
        if check
        else f"Generated {len(expected)} variants from {len(sources)} public images"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
