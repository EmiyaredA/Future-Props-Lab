"""Generate the bundled avatar asset contract independently of retired HTTP APIs."""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

from studio.contracts.media_rendering.character_document import CharacterDocument

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "web/src/shared/live2d/modelSchema.ts"


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return f"Schemas[{json.dumps(schema['$ref'].rsplit('/', 1)[1])}]"
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        properties = schema.get("properties", {})
        if properties:
            required = schema.get("required", [])
            fields = [
                f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
                for name, value in properties.items()
            ]
            return "{ " + " ".join(fields) + " }"
        additional = schema.get("additionalProperties", {})
        return (
            f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
        )
    if kind in ("number", "integer"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    if not schema:
        return "unknown"
    raise ValueError(f"Unsupported avatar schema: {schema}")


def generate() -> str:
    schema = CharacterDocument.model_json_schema(by_alias=True)
    definitions = schema.pop("$defs")
    definitions["CharacterDocument"] = schema
    lines = [
        "// Generated by scripts/generate_avatar_contract.py; do not edit.",
        "// Asset format only: no project management or HTTP operations.",
        "export type Schemas = {",
    ]
    lines += [f"  {json.dumps(name)}: {ts_type(value)};" for name, value in definitions.items()]
    source = "\n".join([*lines, "};", ""])
    return subprocess.run(
        [str(ROOT / "node_modules/.bin/prettier"), "--parser", "typescript"],
        input=source,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit("Stale bundled avatar contract; run contracts:generate")
    else:
        TARGET.write_text(content)


if __name__ == "__main__":
    main()
