export function guideSearchText(page: GuidePage) {
  return [
    page.title,
    page.group,
    page.lead,
    ...page.sections.flatMap((section) => [
      section.title,
      ...(section.paragraphs ?? []),
      ...(section.steps ?? []),
      ...(section.bullets ?? []),
      section.note ?? "",
      ...(section.table?.headers ?? []),
      ...(section.table?.rows.flat() ?? []),
    ]),
  ]
    .join(" ")
    .toLocaleLowerCase("zh-CN");
}
